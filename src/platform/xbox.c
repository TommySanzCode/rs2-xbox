void platform_update_surface(void) {
    const uint32_t started = GetTickCount();
    xbox_display_present(&display, rgbx, cursor, CURSOR_W, CURSOR_H, cursor_x, cursor_y);
    xbox_last_present_ms = GetTickCount() - started;
}
